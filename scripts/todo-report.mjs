// Collects every [TODO: ...] marker from the site's sources into todo-report.md, by file and line.
// Paper pages hide the markers from readers, so this report is the list of open facts.
// Prints the report; exits 1 with STRICT=1 when any marker is left (main-site deploy).
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const files = [];
(function walk(d) {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(mdx|md|ts|astro|json|yaml)$/.test(f)) files.push(p);
  }
})('src');

const rows = [];
for (const f of files.sort()) {
  readFileSync(f, 'utf8').split('\n').forEach((line, i) => {
    for (const m of line.matchAll(/\[TODO[^\]]*\]/g)) rows.push({ f, line: i + 1, todo: m[0].slice(1, -1).replace(/^TODO:?\s*/, '') });
  });
}
const by = {};
for (const r of rows) (by[r.f] ||= []).push(r);
let md = `# Open facts (TODO report)\n\nGenerated by scripts/todo-report.mjs. ${rows.length} open item(s).\n`;
for (const [f, rs] of Object.entries(by)) md += `\n## ${f}\n\n${rs.map((r) => `- line ${r.line}: ${r.todo}`).join('\n')}\n`;
writeFileSync('todo-report.md', md);
console.log(md);
if (process.env.STRICT === '1' && rows.length) {
  console.error(`STRICT: ${rows.length} TODO marker(s) left; see todo-report.md`);
  process.exit(1);
}
