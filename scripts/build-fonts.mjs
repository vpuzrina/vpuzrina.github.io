// One-off: copies the woff2 files this site uses from @fontsource into public/fonts
// and writes src/styles/fonts.css with unicode ranges and size-adjusted fallbacks.
// Run with `node scripts/build-fonts.mjs` after changing weights or subsets.
import { readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { fromFile } = await import('@capsizecss/metrics/entireMetricsCollection').catch(() => ({}));

const fonts = [
  { pkg: 'ibm-plex-serif', family: 'Plex Serif', styles: [['400', 'normal'], ['400', 'italic'], ['600', 'normal']] },
  { pkg: 'ibm-plex-mono', family: 'Plex Mono', styles: [['400', 'normal'], ['500', 'normal']] },
  // IBM Plex Serif and Mono have no Greek, and the figures use α, β, σ, ε. Only the Greek code points
  // come from these two OFL fonts, under the same family names.
  { pkg: 'source-serif-4', family: 'Plex Serif', styles: [['400', 'normal'], ['400', 'italic'], ['600', 'normal']], subsets: ['greek'] },
  { pkg: 'jetbrains-mono', family: 'Plex Mono', styles: [['400', 'normal'], ['500', 'normal']], subsets: ['greek'] },
];
const defaultSubsets = ['cyrillic', 'latin-ext', 'latin'];
let css = '/* Generated by scripts/build-fonts.mjs. Self-hosted IBM Plex, plus Greek from Source Serif 4 and JetBrains Mono (all SIL OFL 1.1). */\n';

for (const f of fonts) {
  for (const [w, s] of f.styles) {
    const src = readFileSync(`node_modules/@fontsource/${f.pkg}/${w}${s === 'italic' ? '-italic' : ''}.css`, 'utf8');
    for (const sub of f.subsets ?? defaultSubsets) {
      const re = new RegExp(`/\\* ${f.pkg}-${sub}-${w}-${s} \\*/[\\s\\S]*?unicode-range: ([^;]+);`);
      const m = src.match(re);
      if (!m) throw new Error(`no ${f.pkg} ${sub} ${w} ${s}`);
      const file = `${f.pkg}-${sub}-${w}-${s}.woff2`;
      copyFileSync(`node_modules/@fontsource/${f.pkg}/files/${file}`, `public/fonts/${file}`);
      css += `@font-face{font-family:'${f.family}';font-style:${s};font-weight:${w};font-display:swap;src:url(/fonts/${file}) format('woff2');unicode-range:${m[1]};}\n`;
    }
  }
}

// Size-adjusted local fallbacks so the swap does not shift layout
const metrics = (name) => require(`@capsizecss/metrics/${name}`);
function fallback(family, target, local, localName) {
  const t = metrics(target), l = metrics(local);
  const tw = t.xWidthAvg / t.unitsPerEm, lw = l.xWidthAvg / l.unitsPerEm;
  const adj = tw / lw;
  const pct = (v) => (v * 100).toFixed(2) + '%';
  return `@font-face{font-family:'${family}';src:local('${localName}');size-adjust:${pct(adj)};ascent-override:${pct(t.ascent / t.unitsPerEm / adj)};descent-override:${pct(Math.abs(t.descent) / t.unitsPerEm / adj)};line-gap-override:${pct(t.lineGap / t.unitsPerEm / adj)};}\n`;
}
css += fallback('Plex Serif Fallback', 'iBMPlexSerif', 'georgia', 'Georgia');
css += fallback('Plex Serif Fallback TNR', 'iBMPlexSerif', 'timesNewRoman', 'Times New Roman');
css += fallback('Plex Mono Fallback', 'iBMPlexMono', 'courierNew', 'Courier New');
writeFileSync('src/styles/fonts.css', css);
console.log('fonts.css written');
